create or replace function public.refresh_community_post_counts()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  affected_post_id bigint;
begin
  affected_post_id := coalesce(new.post_id, old.post_id);

  update public.community_posts
  set
    like_count = (
      select count(*)::integer
      from public.community_likes
      where community_likes.post_id = affected_post_id
    ),
    comment_count = (
      select count(*)::integer
      from public.community_comments
      where community_comments.post_id = affected_post_id
    ),
    updated_at = now()
  where post_id = affected_post_id;

  return coalesce(new, old);
end;
$$;

