create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  display_name text;
begin
  display_name := coalesce(
    nullif(new.raw_user_meta_data ->> 'nickname', ''),
    nullif(new.raw_user_meta_data ->> 'name', ''),
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    split_part(coalesce(new.email, 'traveler'), '@', 1),
    'traveler'
  );

  insert into public.users (
    user_id,
    email,
    nickname,
    profile_image,
    profile_completed,
    approved_at
  )
  values (
    new.id,
    coalesce(new.email, ''),
    display_name,
    coalesce(
      nullif(new.raw_user_meta_data ->> 'profile_image', ''),
      nullif(new.raw_user_meta_data ->> 'avatar_url', ''),
      nullif(new.raw_user_meta_data ->> 'picture', '')
    ),
    false,
    now()
  )
  on conflict (user_id) do update
  set
    email = excluded.email,
    nickname = coalesce(public.users.nickname, excluded.nickname),
    profile_image = coalesce(public.users.profile_image, excluded.profile_image),
    updated_at = now();

  return new;
end;
$$;

