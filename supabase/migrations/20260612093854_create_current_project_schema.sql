create or replace view public.community_feed as
select
  p.post_id,
  p.user_id,
  p.title,
  p.summary,
  p.tags,
  p.location,
  p.category,
  p.type,
  p.like_count,
  p.comment_count,
  p.image_urls,
  p.created_at,
  p.updated_at,
  coalesce(u.nickname, p.nickname) as nickname,
  u.profile_image,
  pref.badge,
  pref.mbti_type
from public.community_posts p
left join public.users u
  on u.user_id = p.user_id
left join public.user_preferences pref
  on pref.user_id = p.user_id;

create or replace view public.community_tags_popular as
select
  trim(tag) as tag,
  count(*)::integer as count
from public.community_posts p
cross join lateral regexp_split_to_table(coalesce(p.tags, ''), '\s*,\s*') as tag
where trim(tag) <> ''
group by trim(tag)
order by count(*) desc, tag asc;

