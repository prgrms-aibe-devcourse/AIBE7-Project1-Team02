grant all on table public.users to service_role;
grant all on table public.user_preferences to service_role;
grant all on table public.destinations to service_role;
grant all on table public.trips to service_role;
grant all on table public.itineraries to service_role;
grant usage, select on sequence public.user_preferences_preference_id_seq to service_role;
grant usage, select on sequence public.destinations_destination_id_seq to service_role;
grant usage, select on sequence public.trips_trip_id_seq to service_role;
grant usage, select on sequence public.itineraries_itinerary_id_seq to service_role;

